"""Builds the avatar model from its source assets and the modelled parts.

    blender -b --factory-startup --python blender/scripts/build_cass.py -- [--level full|lite] [--force] [--output PATH]

`full` writes blender/cass.blend and `lite` blender/cass-lite.blend; both
share one skeleton and one texture. The body is SiroinoSotai, the head is
the face of HENGE's Mizunashi Hiyori (see blender/sources/ and CREDITS.md),
and the hair, ears, tail and outfit are generated by the modules in kitbash/.

The output is deterministic. The scene is stamped as generator output with a
digest of its content; an existing file is only overwritten while it still
matches its stamp, i.e. while nobody has modelled in it. Anything else needs
--force.
"""

import sys
import pathlib

sys.dont_write_bytecode = True
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import argparse

import bpy
import numpy as np
from mathutils import Matrix, Vector

import cass_spec
import validate
from kitbash import atlas, body, common, decals, extras, face, garments, hair, hat, rig, stamp

SOURCES = {
    "body": (cass_spec.SOURCES_DIR / "siroino-body.blend", "siroino-{level}", "siroino-armature"),
    "face": (cass_spec.SOURCES_DIR / "henge-face.blend", "henge-face", "henge-armature"),
}
FACE_TEXTURE = cass_spec.SOURCES_DIR / "henge-face.png"
FACE_NORMAL = cass_spec.SOURCES_DIR / "henge-face-normal.png"
BODY_NORMALS = {level: cass_spec.SOURCES_DIR / f"siroino-normal-{level}.png" for level in cass_spec.LEVELS}

SKIN_MESH = "Skin"

# The head is the face's own size times this, on the body at its own size; the
# design draws the head large. Then the whole figure is scaled to the height
# in Spec/proportions.json.
HEAD_SCALE = 1.15
# Radius of the neck where head and body meet, in the body base's own units.
NECK_SEAM_RADIUS = 0.0345
# How far the head is set down onto the neck, and how far the body's neck carries on up inside it.
HEAD_DROP = 0.008
NECK_OVERLAP = 0.030
# Shape keys that show modelled marks (kitbash/decals.py) instead of moving the face.
DECAL_KEYS = ("照れ", "涙")


# How finely the modelled parts are divided at each level.
DETAIL = {"full": 1.0, "lite": 0.5}
PARTS = (garments.build_shorts, garments.build_sweater, garments.build_boots,
         hair.build_hair, extras.build_ears, extras.build_tail, hat.build_hat)


def parse_args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    parser = argparse.ArgumentParser(prog="build_cass.py", description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--level", choices=sorted(cass_spec.LEVELS), default="full")
    parser.add_argument("--force", action="store_true", help="overwrite even a hand-modelled .blend")
    parser.add_argument("--output", help="where to save (default: the level's .blend)")
    parser.add_argument("--draft", action="store_true", help="save even when validation fails, to look at work in progress")
    return parser.parse_args(argv)


def guard_existing(path, force):
    if not path.exists() or force:
        return
    bpy.ops.wm.open_mainfile(filepath=str(path))
    if not stamp.is_untouched():
        raise SystemExit(
            f"build_cass: {path} is not untouched generator output (missing or stale "
            f"'{cass_spec.GENERATED_PROP}' stamp); refusing to overwrite hand-made work. Pass --force to replace it."
        )


def make_material():
    material = bpy.data.materials.new(cass_spec.MATERIAL_NAME)
    tree = material.node_tree
    bsdf = next(node for node in tree.nodes if node.type == "BSDF_PRINCIPLED")
    texture = tree.nodes.new("ShaderNodeTexImage")
    texture.image = bpy.data.images.load(str(cass_spec.ATLAS_PNG))
    texture.location = (-320, 300)
    tree.links.new(texture.outputs["Color"], bsdf.inputs["Base Color"])
    bsdf.inputs["Roughness"].default_value = 1.0
    # Solid-mode texture colouring shows the active image node.
    tree.nodes.active = texture
    return material


def assemble(level, collection):
    """Body, head and skeleton, joined and scaled to the avatar's height. Returns a context dict."""
    body_path, body_name, body_rig = SOURCES["body"]
    face_path, face_name, face_rig = SOURCES["face"]
    body_objects = common.append_objects(body_path, [body_name.format(level=level), body_rig])
    face_objects = common.append_objects(face_path, [face_name, face_rig])
    skin, source_rig = body_objects[body_name.format(level=level)], body_objects[body_rig]
    head, head_rig = face_objects[face_name], face_objects[face_rig]

    skeleton = cass_spec.load_skeleton()
    armature = rig.adopt(source_rig, skeleton["armature"], collection)
    body.prepare(skin)
    rig.rename_groups(skin)

    head_joint = rig.head_of(armature, "Head")
    head_joint.z -= HEAD_DROP
    eyes = face.prepare(head, head_rig, head_joint, HEAD_SCALE)
    loop, centre, radius = face.neck_opening(head, below=head_joint.z + 0.03 * HEAD_SCALE)
    pairs = face.overlay_pairs(head)
    face.narrow_neck(head, loop, centre, radius, NECK_SEAM_RADIUS, reach=0.022 * HEAD_SCALE)
    body.fit_neck(skin, centre, NECK_SEAM_RADIUS - 0.0012, NECK_OVERLAP)
    face.seal_neck(head, loop, skin)

    # The body's flat skin colour is the face texture's own skin tone.
    mesh = head.data
    source_uv = common.get_uv(mesh, mesh.uv_layers[0].name)
    skin_loops = face.face_classes(mesh)[common.loop_polygons(mesh)] == face.SKIN
    tone_uv = source_uv[skin_loops][::7]
    palette = atlas.build(FACE_TEXTURE, cass_spec.PALETTE_PNG, cass_spec.PALETTE_JSON,
                          cass_spec.ATLAS_PNG, cass_spec.ATLAS_JSON, pairs, tone_uv)

    atlas.build_normal(FACE_NORMAL, BODY_NORMALS, cass_spec.ATLAS_NORMAL_PNG)

    blendshapes = cass_spec.load_blendshapes()
    missing = face.rebuild_shape_keys(head, blendshapes["all"], blend_width=0.006 * HEAD_SCALE)
    lacking = [name for name in missing if name in blendshapes["required"] and name not in DECAL_KEYS]
    if lacking:
        raise SystemExit(f"build_cass: no recipe for required shape key(s): {lacking}")

    # Head UVs: the face keeps its place in the atlas (wrapped into 0..1); the overlays moved down.
    classes = face.face_classes(mesh)
    polygon_of_loop = common.loop_polygons(mesh)
    first_u = np.array([source_uv[p.loop_start, 0] for p in mesh.polygons])
    source_uv[:, 0] -= np.floor(first_u)[polygon_of_loop]
    source_uv[classes[polygon_of_loop] == face.OVERLAY, 1] -= atlas.OVERLAY_SHIFT
    mesh.uv_layers[0].name = cass_spec.UV_PALETTE
    common.ensure_uv_layers(mesh)
    common.set_uv(mesh, cass_spec.UV_PALETTE, source_uv)

    tiles = cass_spec.load_tiles()
    material = make_material()
    head.name = mesh.name = blendshapes["mesh"]
    common.finish_mesh(head, collection, armature, material, tiles,
                       ["face.eyes" if c != face.SKIN else "always" for c in classes])
    skin.name = skin.data.name = SKIN_MESH
    # The body is flat skin colour, but keeps its own UVs, moved into a skin-coloured region
    # of the atlas, so that the body base's normal map (in the normal atlas) lands on it.
    # The first UV layer is the one the base's normal map is drawn for (the rest are for its
    # nail textures). It is read here, from the mesh as it now is: trimming the neck re-orders
    # the mesh's corners, and UVs read before that would land on the wrong ones.
    skin.data.uv_layers[0].name = cass_spec.UV_PALETTE
    own_uv = common.get_uv(skin.data, cass_spec.UV_PALETTE)
    common.ensure_uv_layers(skin.data)
    common.set_uv(skin.data, cass_spec.UV_PALETTE, atlas.body_uv(own_uv, level))
    common.finish_mesh(skin, collection, armature, material, tiles, body.zones(skin.data))

    crown = common.coords(mesh)[:, 2].max()
    # The eye bones point up with their Z axis forward, like the head they hang from, so that
    # in Unity a turn about X is the gaze going up or down and a turn about Y is it going
    # sideways, whichever frame the rotation is read in.
    rig.add_bones(armature, [
        (f"Eye.{side}", eyes[side], eyes[side] + Vector((0.0, 0.0, 0.03)), "Head", (0.0, -1.0, 0.0)) for side in "LR"
    ])
    rig.move_tail(armature, "Head", (head_joint.x, head_joint.y, crown))
    bpy.data.objects.remove(head_rig)

    # Scale to the avatar's height, standing on the soles its boots will have.
    proportions = cass_spec.load_proportions()
    floor = common.coords(skin.data)[:, 2].min()
    scale = proportions["height"] / (crown - floor)
    lift = proportions["bootHeelHeight"]
    place = Matrix.Translation((0.0, 0.0, lift - floor * scale)) @ Matrix.Scale(scale, 4)
    for obj in (skin, head):
        obj.data.transform(place, shape_keys=True)
        obj.data.update()
    armature.data.transform(place)
    bpy.context.view_layer.update()
    print(f"build_cass: head x{HEAD_SCALE}, figure x{scale:.4f}, soles lifted {lift} m")

    return {"level": level, "collection": collection, "armature": armature, "material": material, "palette": palette,
            "tiles": tiles, "skin": skin, "head": head, "scale": scale, "lift": lift}


def build_scene(level):
    scene = bpy.context.scene
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.scale_length = 1.0
    collection = bpy.data.collections.new(cass_spec.EXPORT_COLLECTION)
    scene.collection.children.link(collection)
    context = assemble(level, collection)
    context["detail"] = DETAIL[level]
    decals.build(context["head"], context["palette"], context["tiles"])
    for build in PARTS:
        build(context)
    scene[cass_spec.LEVEL_PROP] = level
    return scene


def main():
    args = parse_args()
    output = pathlib.Path(args.output).resolve() if args.output else cass_spec.LEVELS[args.level]["blend"]
    guard_existing(output, args.force)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = build_scene(args.level)

    report = validate.validate()
    report.print()
    if report.errors and not args.draft:
        raise SystemExit("build_cass: the model fails validation; nothing was saved")

    stamp.stamp(scene)
    output.parent.mkdir(parents=True, exist_ok=True)
    # No .blend1 backups: the file is reproducible from this script.
    bpy.context.preferences.filepaths.save_version = 0
    bpy.ops.wm.save_as_mainfile(filepath=str(output), compress=True)
    # The texture is referenced relative to the .blend so the repo can live
    # anywhere. A relative path only means something once the file has a
    # location, hence the second save.
    bpy.ops.file.make_paths_relative()
    bpy.ops.wm.save_mainfile(compress=True)
    print(f"build_cass: wrote {output}")


main()
